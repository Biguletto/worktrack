from datetime import date

from django.core.management.base import BaseCommand, CommandError
from django.db.models import Q
from django.utils import timezone

from eqrApp.models import AttendanceRecord, EmployeeProfile, Holiday, LeaveApplication


class Command(BaseCommand):
    help = 'Create scheduled absence records for active employees who have no attendance entry.'

    def add_arguments(self, parser):
        parser.add_argument('--date', dest='target_date', help='Date to process in YYYY-MM-DD format (defaults to today).')

    def handle(self, *args, **options):
        target = timezone.localdate()
        if options.get('target_date'):
            try:
                target = date.fromisoformat(options['target_date'])
            except ValueError as exc:
                raise CommandError('Use the date format YYYY-MM-DD.') from exc

        if target > timezone.localdate():
            raise CommandError('Absences cannot be recorded for a future date.')
        if target.weekday() >= 5 or Holiday.objects.filter(date=target, is_active=True).exists():
            self.stdout.write(self.style.WARNING(f'{target} is a weekend or configured holiday. No absences created.'))
            return

        employees = EmployeeProfile.objects.filter(
            Q(hire_date__isnull=True) | Q(hire_date__lte=target),
            employment_status='active', user__is_active=True, role__in=['employee', 'supervisor'],
        )
        created = 0
        for employee in employees.iterator():
            approved_leave = LeaveApplication.objects.filter(
                employee=employee, status='approved',
                start_date__lte=target, end_date__gte=target,
            ).exists()
            if approved_leave:
                continue
            _, was_created = AttendanceRecord.objects.get_or_create(
                employee=employee,
                attendance_date=target,
                defaults={'status': 'absent', 'source': 'scheduled', 'remarks': 'Generated by the scheduled absence process.'},
            )
            created += int(was_created)
        self.stdout.write(self.style.SUCCESS(f'Created {created} absence records for {target}.'))
